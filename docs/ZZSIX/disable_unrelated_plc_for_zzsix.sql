-- =============================================================================
-- ZZSIX 现场机：禁用与 PACK 六面检无关的 PLC（消除日志里「口琴管涂胶 / 欧姆龙伺服」刷屏）
-- =============================================================================
-- 原因：PLCService 会连接库里所有 IsEnable=1 的 PLC；
--       共享库若曾跑过 BoxGluing / 其它项目种子，会一直重连 192.168.3.220 等地址。
-- 用法：在现场 MySQL 执行本脚本后，完整重启 SEVB（勿热替换）。
-- 注意：若本机还要跑「口琴管涂胶监测」，不要执行本脚本（或事后把对应行改回 IsEnable=1）。
-- =============================================================================

UPDATE plc_config
SET IsEnable = 0
WHERE Name IN (
    '口琴管涂胶PLC',
    '欧姆龙伺服PLC'
)
AND IsEnable = 1;

